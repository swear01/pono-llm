def test_build_hot_variables(simple_path):
    info = parse_btor2(simple_path)
    refs = ["state6", "state7"]
    hvars = build_hot_variables(info, refs)
    assert len(hvars) == 2
    by_ref = {h["ref"]: h for h in hvars}
    assert by_ref["state6"]["width"] == 8
    assert by_ref["state6"]["verilog"] == "wr_ptr"
    assert by_ref["state7"]["verilog"] == "rd_ptr"
    assert "init" in by_ref["state6"]


def test_build_hot_variables_no_symbol():
    """States without meaningful symbols should not have 'verilog' key."""
    content = textwrap.dedent("""\
    ; BTOR description for module foo.
    1 sort bitvec 4
    2 state 1 $auto$clk:42
    """)
    f = tempfile.NamedTemporaryFile(mode="w", suffix=".btor2", delete=False)
    f.write(content)
    f.close()
    info = parse_btor2(f.name)
    os.unlink(f.name)
    hvars = build_hot_variables(info, ["state2"])
    assert "verilog" not in hvars[0]


