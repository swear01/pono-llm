def make_btor2(content: str) -> str:
    """Write BTOR2 content to a temp file and return the path."""
    f = tempfile.NamedTemporaryFile(mode="w", suffix=".btor2", delete=False)
    f.write(textwrap.dedent(content))
    f.close()
    return f.name


