def test_hot_refs_basic(simple_path):
    info = parse_btor2(simple_path)
    # bad(line 19) expr=18: not→17→eq(8,16)→sub(6,7)
    # depth=3 reaches state8 (via eq's direct arg); depth=4 reaches state6,state7
    refs3 = hot_refs_near_bad(info, depth=3)
    assert "state8" in refs3          # count is 3 hops from bad
    refs4 = hot_refs_near_bad(info, depth=4)
    assert "state6" in refs4 or "state7" in refs4   # wr_ptr/rd_ptr are 4 hops


def test_hot_refs_empty_when_no_bad():
    import io
    content = "1 sort bitvec 1\n2 state 1 x\n"
    f = tempfile.NamedTemporaryFile(mode="w", suffix=".btor2", delete=False)
    f.write(content)
    f.close()
    info = parse_btor2(f.name)
    os.unlink(f.name)
    refs = hot_refs_near_bad(info, depth=3)
    assert refs == []


